function rotr(x, n) {
  return (x >>> n) | (x << (32 - n));
}

export function sha256Bytes(bytes) {
  const bitLen = bytes.length * 8;
  const withPad = ((bytes.length + 9 + 63) >> 6) << 6;
  const buf = new Uint8Array(withPad);
  buf.set(bytes, 0);
  buf[bytes.length] = 0x80;
  const view = new DataView(buf.buffer);
  view.setUint32(withPad - 8, Math.floor(bitLen / 0x100000000), false);
  view.setUint32(withPad - 4, bitLen >>> 0, false);

  let h0 = 0x6a09e667, h1 = 0xbb67ae85, h2 = 0x3c6ef372, h3 = 0xa54ff53a;
  let h4 = 0x510e527f, h5 = 0x9b05688c, h6 = 0x1f83d9ab, h7 = 0x5be0cd19;

  const w = new Uint32Array(64);
  for (let off = 0; off < withPad; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(off + i * 4, false);
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >>> 3);
      const s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }
    let a = h0, b = h1, c = h2, d = h3, e = h4, f = h5, g = h6, h = h7;
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + S1 + ch + SHA256_K[i] + w[i]) >>> 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) >>> 0;
      h = g; g = f; f = e;
      e = (d + t1) >>> 0;
      d = c; c = b; b = a;
      a = (t1 + t2) >>> 0;
    }
    h0 = (h0 + a) >>> 0; h1 = (h1 + b) >>> 0; h2 = (h2 + c) >>> 0; h3 = (h3 + d) >>> 0;
    h4 = (h4 + e) >>> 0; h5 = (h5 + f) >>> 0; h6 = (h6 + g) >>> 0; h7 = (h7 + h) >>> 0;
  }

  const out = new Uint8Array(32);
  const ov = new DataView(out.buffer);
  [h0, h1, h2, h3, h4, h5, h6, h7].forEach((v, i) => ov.setUint32(i * 4, v, false));
  return out;
}

export function sha256Hex(str) {
  return toHex(sha256Bytes(utf8Bytes(str)));
}

export function hmacSha256Hex(keyStr, msgStr) {
  let key = utf8Bytes(keyStr);
  if (key.length > 64) key = sha256Bytes(key);
  const pad = new Uint8Array(64);
  pad.set(key, 0);
  const ipad = new Uint8Array(64);
  const opad = new Uint8Array(64);
  for (let i = 0; i < 64; i++) {
    ipad[i] = pad[i] ^ 0x36;
    opad[i] = pad[i] ^ 0x5c;
  }
  const inner = sha256Bytes(concatBytes(ipad, utf8Bytes(msgStr)));
  return toHex(sha256Bytes(concatBytes(opad, inner)));
}

export function randomHex(nBytes) {
  const b = new Uint8Array(nBytes);
  const c = typeof crypto !== 'undefined' && crypto.getRandomValues ? crypto : null;
  if (c) c.getRandomValues(b);
  else for (let i = 0; i < nBytes; i++) b[i] = Math.floor(Math.random() * 256);
  return toHex(b);
}

/** 事件流 token：8–91 位 URL-safe，仅 A-Z a-z 0-9 - _ . ~ */
export function newEventId() {
  return 'evt-' + randomHex(12);
}

/** Request-Id：16–128 位 URL-safe */
export function newRequestId() {
  return randomHex(16);
}